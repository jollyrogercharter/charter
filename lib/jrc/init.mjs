import { existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { PILLARS, SCHEMA_URL, SPEC_VERSION } from "./constants.mjs";

// Filename hints only; init never turns a candidate into a claim.
const HINTS = {
  code_rights: [/^(LICENSE|LICENCE|COPYING|UNLICENSE)(\..*)?$/i, /^NOTICE(\..*)?$/i, /^package-lock\.json$|^yarn\.lock$|^pnpm-lock\.yaml$|^Cargo\.lock$|^go\.sum$|^poetry\.lock$|^Gemfile\.lock$|^composer\.lock$/],
  development: [/^README(\..*)?$/i, /^AGENTS\.md$|^CLAUDE\.md$|^CONTRIBUTING(\..*)?$/i, /^\.github\/workflows\/.+\.ya?ml$/, /^(test|tests|spec)\/$/, /^docs\/$/],
  data: [/privacy/i, /export/i, /lexicons?\//i],
  operations: [/^DEPLOY(MENT)?(\..*)?$/i, /^Dockerfile$|^docker-compose\.ya?ml$|^compose\.ya?ml$/, /^RUNBOOK|^SECURITY(\..*)?$/i, /\.tf$|^infra\//],
  economics: [/cost/i, /budget/i, /ledger/i],
  governance: [/^GOVERNANCE(\..*)?$/i, /^CODE_OF_CONDUCT(\..*)?$/i, /^MAINTAINERS|^CODEOWNERS$|^\.github\/CODEOWNERS$/i, /^\.github\/ISSUE_TEMPLATE\/$/],
};

function listShallow(root) {
  const out = [];
  const add = (rel, isDir) => out.push(isDir ? `${rel}/` : rel);
  for (const d of readdirSync(root, { withFileTypes: true })) {
    if (d.name === "node_modules" || d.name === ".git") continue;
    add(d.name, d.isDirectory());
    if (d.isDirectory() && [".github", "docs", "launch", "infra"].includes(d.name)) {
      for (const e of readdirSync(path.join(root, d.name), { withFileTypes: true })) {
        add(`${d.name}/${e.name}`, e.isDirectory());
        if (e.isDirectory() && d.name === ".github") for (const f of readdirSync(path.join(root, d.name, e.name))) add(`${d.name}/${e.name}/${f}`, false);
      }
    }
  }
  return out.sort();
}

export function initManifest(root, { name, today = new Date().toISOString().slice(0, 10) } = {}) {
  const files = existsSync(root) ? listShallow(root) : [];
  const pillars = {};
  for (const { key, asks } of PILLARS) {
    const candidates = files.filter((f) => HINTS[key].some((re) => re.test(f)));
    pillars[key] = { status: "not-started", claims: [], gaps: [asks], ...(candidates.length ? { candidates } : {}) };
  }
  return {
    $schema: SCHEMA_URL,
    jrc: SPEC_VERSION,
    project: { name: name || path.basename(path.resolve(root)) },
    assessment: { kind: "self", assessor: "REPLACE: your name, handle or role (no email)", date: today, method: "Self-assessment with jrc; edit claims and evidence by hand." },
    pillars,
    limitations: ["Starter manifest generated by jrc init; nothing has been assessed yet."],
  };
}
